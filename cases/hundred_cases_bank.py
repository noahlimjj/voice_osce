"""
hundred_cases_bank.py: 85 High-Yield OSCE Stations (case_16 to case_100) completing the 100-Case OSCEBlitz Bank.
Integrates the Approach-Based Diagnostic Framework (Harrison's, Kumar & Clark, Oxford Handbook of Clinical Medicine).
"""

from typing import Dict, List, Any
from voice_osce.cases.case_schema import (
    OSCECase, CandidateBrief, PatientPersona, InformationGate,
    GateCategory, PerturbationData, Differential, DifferentialTier,
    VivaQuestion, CognitiveTrap
)


def make_station(
    case_id: str,
    specialty: str,
    title: str,
    setting: str,
    patient_name: str,
    age: int,
    gender: str,
    occupation: str,
    complaint: str,
    vitals: Dict[str, str],
    voice_id: str,
    cues: List[str],
    socrates_trig: List[str],
    socrates_resp: str,
    rf1_key: str,
    rf1_trig: List[str],
    rf1_resp: str,
    rf2_key: str,
    rf2_trig: List[str],
    rf2_resp: str,
    pmhx_trig: List[str],
    pmhx_resp: str,
    social_trig: List[str],
    social_resp: str,
    ice_resp: str,
    pert_title: str,
    pert_desc: str,
    pert_findings: Dict[str, str],
    pert_shifts: Dict[str, int],
    pert_rationale: str,
    primary_dx: str,
    primary_sup: List[str],
    mnm_dx: str,
    mnm_sup: List[str],
    mnm_ref: List[str],
    sec_dx: str,
    sec_sup: List[str],
    viva1_q: str,
    viva1_rubric: str,
    viva1_keys: List[str],
    viva2_q: str,
    viva2_rubric: str,
    viva2_keys: List[str],
    trap_name: str,
    trap_desc: str,
    trap_cond: str,
    trap_rem: str,
) -> OSCECase:
    return OSCECase(
        case_id=case_id,
        specialty=specialty,
        title=title,
        brief=CandidateBrief(
            setting=setting,
            patient_name=patient_name,
            age=age,
            gender=gender,
            occupation=occupation,
            presenting_complaint=complaint,
            triage_vitals=vitals,
            instructions=(
                f"BLITZ MODE: Rapidly evaluate {patient_name} ({age}yo {gender}) presenting with {complaint.lower()}. "
                "Unlock critical history and red flags, interpret interim bedside investigations, and formulate an acute management plan."
            ),
        ),
        persona=PatientPersona(
            name=patient_name,
            voice_id=voice_id,
            speech_rate="+0%",
            pain_level=7,
            temperament="anxious",
            behavioral_cues=cues,
        ),
        gates=[
            InformationGate(
                key="hpi_socrates",
                category=GateCategory.SOCRATES,
                trigger_concepts=socrates_trig + ["start", "onset", "when", "describe", "character", "pain", "symptoms", "long", "where", "severity"],
                response_text=socrates_resp,
                mandatory_for_safety=False,
            ),
            InformationGate(
                key=rf1_key,
                category=GateCategory.RED_FLAG,
                trigger_concepts=rf1_trig,
                response_text=rf1_resp,
                mandatory_for_safety=True,
            ),
            InformationGate(
                key=rf2_key,
                category=GateCategory.RED_FLAG,
                trigger_concepts=rf2_trig,
                response_text=rf2_resp,
                mandatory_for_safety=True,
            ),
            InformationGate(
                key="pmhx_drugs_allergies",
                category=GateCategory.PAST_HISTORY,
                trigger_concepts=pmhx_trig + ["past medical", "history", "conditions", "medications", "drugs", "tablets", "allergies", "allergy"],
                response_text=pmhx_resp,
                mandatory_for_safety=True,
            ),
            InformationGate(
                key="social_epi_history",
                category=GateCategory.SOCIAL_HISTORY,
                trigger_concepts=social_trig + ["smoke", "alcohol", "occupation", "work", "travel", "family", "home", "diet"],
                response_text=social_resp,
                mandatory_for_safety=False,
            ),
            InformationGate(
                key="ice_concerns",
                category=GateCategory.ICE,
                trigger_concepts=["worry", "worried", "concern", "expect", "think", "afraid", "scared", "ideas"],
                response_text=ice_resp,
                mandatory_for_safety=False,
            ),
        ],
        perturbation=PerturbationData(
            trigger_turn=3,
            title=pert_title,
            description=pert_desc,
            findings=pert_findings,
            expected_shifts=pert_shifts,
            expert_rationale=pert_rationale,
        ),
        differentials=[
            Differential(
                name=primary_dx,
                tier=DifferentialTier.PRIMARY,
                supporting_features=primary_sup,
                refuting_features=[],
                prior_probability=0.75,
                posterior_probability=0.97,
            ),
            Differential(
                name=mnm_dx,
                tier=DifferentialTier.MUST_NOT_MISS,
                supporting_features=mnm_sup,
                refuting_features=mnm_ref,
                prior_probability=0.15,
                posterior_probability=0.02,
            ),
            Differential(
                name=sec_dx,
                tier=DifferentialTier.SECONDARY,
                supporting_features=sec_sup,
                refuting_features=["Excluded by definitive bedside/imaging perturbation findings"],
                prior_probability=0.10,
                posterior_probability=0.01,
            ),
        ],
        viva_questions=[
            VivaQuestion(
                prompt=viva1_q,
                target_rubric=viva1_rubric,
                max_marks=15,
                key_points_required=viva1_keys,
            ),
            VivaQuestion(
                prompt=viva2_q,
                target_rubric=viva2_rubric,
                max_marks=15,
                key_points_required=viva2_keys,
            ),
        ],
        cognitive_traps=[
            CognitiveTrap(
                trap_name=trap_name,
                description=trap_desc,
                trigger_condition=trap_cond,
                remediation_advice=trap_rem,
            )
        ],
    )


